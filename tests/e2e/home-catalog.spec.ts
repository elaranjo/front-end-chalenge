test('desktop card favorite remains available on hover and keyboard focus', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('http://127.0.0.1:5173/')
  const card = page.locator('.home-card').first()
  const favorite = card.getByRole('link', { name: /Entrar para favoritar/ })
  await expect(favorite).toHaveCSS('opacity', '0')
  await card.hover()
  await expect(favorite).toHaveCSS('opacity', '1')
  await page.mouse.move(0, 0)
  await favorite.focus()
  await expect(favorite).toBeFocused()
  await expect(favorite).toHaveCSS('opacity', '1')
})
