import { expect, test } from '@playwright/test'

test('login reports stock adjustments and does not merge the visitor cart twice', async ({ page }) => {
  await page.setViewportSize({ width: 414, height: 896 })
  await page.goto('http://127.0.0.1:5173/nfts/emerald-ape-042')
  await page.getByRole('button', { name: '1/10', exact: true }).click()
  await page.getByRole('button', { name: 'Aumentar quantidade' }).click()
  await page.getByRole('button', { name: 'Adicionar ao carrinho' }).click()
  await expect(page.getByRole('status')).toHaveText('NFT adicionado ao carrinho.')
  const updated = await page.evaluate(async () => (await fetch('/api/v1/__mock/actions', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ action: 'updateNft', payload: { nftId: 'emerald-ape-042', editionId: 'one-of-ten', available: 1 } }) })).ok)
  expect(updated).toBe(true)
  await page.goto('http://127.0.0.1:5173/login?returnTo=%2Fcart')
  await page.getByLabel('E-mail', { exact: true }).fill('colecionador.a@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('DemoA!2026')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  const notice = page.getByRole('status', { name: 'Ajustes do carrinho' })
  await expect(notice).toContainText('1 de 2 adicionados')
  await notice.getByRole('button', { name: 'Continuar' }).click()
  await expect(page).toHaveURL(/\/cart$/)
  await expect(page.getByText('Emerald Ape #042')).toBeVisible()
  await page.reload()
  await expect(page.getByText('Emerald Ape #042')).toBeVisible()
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('http://127.0.0.1:5173/profile')
  await page.getByRole('button', { name: 'Sair', exact: true }).click()
  await page.goto('http://127.0.0.1:5173/login?returnTo=%2Fcart')
  await page.getByLabel('E-mail', { exact: true }).fill('colecionador.a@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('DemoA!2026')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(/\/cart$/)
  await expect(page.getByText('Emerald Ape #042')).toBeVisible()
  const cart = await page.evaluate(async () => {
    const token = localStorage.getItem('kurio.session-token')
    return (await (await fetch('/api/v1/cart', { headers: { Authorization: `Bearer ${token}` } })).json()).lines.map((line: { quantity: number }) => line.quantity)
  })
  expect(cart).toEqual([1])
})

test('a pending merge remains recoverable outside auth after a refresh', async ({ page }) => {
  await page.setViewportSize({ width: 414, height: 896 })
  await page.goto('http://127.0.0.1:5173/login?returnTo=%2Fcart')
  await page.getByLabel('E-mail', { exact: true }).fill('colecionador.a@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('DemoA!2026')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(/\/cart$/)
  const visitor = await page.evaluate(async () => {
    const visitorId = localStorage.getItem('kurio.visitor-id')!
    const response = await fetch('/api/v1/cart/items', { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-Visitor-Id': visitorId, 'If-Match': '0', 'X-Mutation-Id': crypto.randomUUID() }, body: JSON.stringify({ nftId: 'emerald-ape-042', editionId: 'one-of-ten', quantity: 2 }) })
    if (!response.ok) throw new Error(`Unable to seed visitor cart: ${response.status}`)
    localStorage.setItem('kurio.pending-cart-merge', JSON.stringify({ ownerUserId: 'collector-a', visitorId }))
    return visitorId
  })
  await page.reload()
  const notice = page.getByRole('status', { name: 'Sincronização do carrinho' })
  await expect(notice).toContainText('ainda não foi sincronizado')
  await notice.getByRole('button', { name: 'Tentar novamente' }).click()
  await expect(notice).toContainText('Carrinho sincronizado')
  await expect(page.getByText('Emerald Ape #042')).toBeVisible()
  const state = await page.evaluate(async () => {
    const token = localStorage.getItem('kurio.session-token')
    return { pending: localStorage.getItem('kurio.pending-cart-merge'), visitor: localStorage.getItem('kurio.visitor-id'), lines: (await (await fetch('/api/v1/cart', { headers: { Authorization: `Bearer ${token}` } })).json()).lines.map((line: { quantity: number }) => line.quantity) }
  })
  expect(state.pending).toBeNull()
  expect(state.visitor).not.toBe(visitor)
  expect(state.lines).toEqual([2])
})
