import { expect, test } from '@playwright/test'

for (const width of [390, 1440]) {
  test(`collector completes a simulated purchase through the UI at ${width}px`, async ({ page }) => {
    test.setTimeout(60000)
    await page.setViewportSize({ width, height: 900 })
    await page.goto('http://127.0.0.1:5173/')
    await page.getByRole('link', { name: /Emerald Ape #042/ }).first().click()
    await expect(page).toHaveURL(/\/nfts\/emerald-ape-042$/)
    await page.getByRole('button', { name: '1/10', exact: true }).click()
    await page.getByRole('button', { name: 'Aumentar quantidade', exact: true }).click()
    await page.getByRole('button', { name: 'Comprar NFT', exact: true }).click()
    await expect(page).toHaveURL(/\/cart$/)
    await expect(page.locator('.cart-line').filter({ hasText: 'Emerald Ape #042' })).toContainText('2.38 ETH')
    await page.getByRole('button', { name: 'Conectar e finalizar' }).click()
    await page.getByLabel('E-mail', { exact: true }).fill('colecionador.a@kurio.test')
    await page.getByLabel('Senha', { exact: true }).fill('DemoA!2026')
    await page.getByRole('button', { name: 'Entrar', exact: true }).click()
    await expect(page).toHaveURL(/\/checkout$/)
    await page.getByRole('link', { name: 'Cadastrar carteira' }).click()
    const wallet = page.getByRole('form', { name: 'Carteira principal' })
    await wallet.getByLabel('Nome de exibição').fill('Colecionador')
    await wallet.getByLabel('Apelido da carteira').fill('Principal')
    await wallet.getByLabel('Rede').selectOption('ethereum')
    await wallet.getByLabel('Nome do perfil').fill('Perfil')
    await wallet.getByLabel('Endereço da carteira').fill(`0x${'a'.repeat(40)}`)
    await wallet.getByLabel('Tipo de carteira').selectOption('metamask')
    await wallet.getByLabel('Código de indicação').fill('DEMO')
    await wallet.getByLabel('E-mail').fill('a@kurio.test')
    await wallet.getByLabel('Nome ENS').fill('colecionador')
    await wallet.getByRole('button', { name: 'Salvar carteira' }).click()
    await expect(wallet.getByRole('status')).toHaveText('Carteira salva.')
    await page.goto('http://127.0.0.1:5173/checkout')
    await page.getByLabel(/Carteira principal — Principal/).click()
    if (width < 1280) await page.getByRole('button', { name: 'Continuar', exact: true }).click()
    await page.getByRole('button', { name: 'Conectar carteira', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Confirmar compra', exact: true })).toBeEnabled()
    await page.getByRole('button', { name: 'Revisar dados' }).click()
    const review = page.getByRole('dialog', { name: 'Revisão dos dados' })
    await expect(review).toContainText('Emerald Ape #042')
    await expect(review).toContainText('Subtotal')
    await expect(review).toContainText('Taxa de rede')
    await expect(review).toContainText('Total')
    await review.getByRole('button', { name: 'Fechar' }).click()
    const order = page.waitForResponse((response) => response.url().endsWith('/api/v1/orders') && response.request().method() === 'POST' && response.ok())
    await page.getByRole('button', { name: 'Confirmar compra', exact: true }).click()
    await order
    await expect(page.getByRole('heading', { name: 'Seus NFTs agora estão na sua carteira' })).toBeVisible({ timeout: 15000 })
    await expect(page.locator('.order-item')).toContainText('Emerald Ape #042')
    await expect(page.locator('.order-item')).toContainText('2.38 ETH')
    await expect(page.getByText(/Nenhuma transação blockchain real/)).toBeVisible()
    await page.goto('http://127.0.0.1:5173/cart')
    await expect(page.getByText('Seu carrinho está vazio.')).toBeVisible()
  })
}
