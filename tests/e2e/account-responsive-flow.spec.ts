import { expect, test } from '@playwright/test'

for (const width of [390, 1440]) {
  test(`profile and independent wallets persist and are usable at checkout at ${width}px`, async ({ page }) => {
    test.setTimeout(60000)
    await page.setViewportSize({ width, height: width === 390 ? 844 : 900 })
    await page.goto('http://127.0.0.1:5173/profile')
    await page.getByLabel('E-mail', { exact: true }).fill('colecionador.a@kurio.test')
    await page.getByLabel('Senha', { exact: true }).fill('DemoA!2026')
    await page.getByRole('button', { name: 'Entrar', exact: true }).click()
    await page.getByLabel('Nome de exibição').fill('Nome atualizado')
    await page.getByLabel('Senha atual', { exact: true }).fill('incorreta')
    await page.getByLabel('Nova senha', { exact: true }).fill('NovaSenha!2026')
    await page.getByLabel('Confirmar nova senha', { exact: true }).fill('NovaSenha!2026')
    await page.getByRole('button', { name: 'Salvar', exact: true }).click()
    await expect(page.getByText('Senha atual incorreta').first()).toBeVisible()
    await page.getByLabel('Senha atual', { exact: true }).fill('DemoA!2026')
    const image = await page.evaluate(async () => {
      const canvas = document.createElement('canvas'); canvas.width = 2; canvas.height = 2
      const blob = await new Promise<Blob>((resolve) => canvas.toBlob((value) => resolve(value!), 'image/png'))
      return Array.from(new Uint8Array(await blob.arrayBuffer()))
    })
    await page.locator('input[type=file]').setInputFiles({ name: 'avatar.png', mimeType: 'image/png', buffer: Buffer.from(image) })
    await page.getByRole('button', { name: 'Salvar', exact: true }).click()
    await expect(page.getByRole('status')).toHaveText('Perfil salvo.')
    await page.reload()
    await expect(page.getByLabel('Nome de exibição')).toHaveValue('Nome atualizado')
    await expect(page.getByAltText('Avatar do perfil')).toBeVisible()
    await page.goto('http://127.0.0.1:5173/wallets')
    const primary = page.getByRole('form', { name: 'Carteira principal' })
    await primary.getByRole('button', { name: 'Salvar carteira' }).click()
    await expect(primary.getByRole('alert')).toHaveText('Confira os campos destacados.')
    await primary.getByLabel('Nome de exibição').fill('Colecionador')
    await primary.getByLabel('Apelido da carteira').fill('Principal')
    await primary.getByLabel('Rede').selectOption('ethereum')
    await primary.getByLabel('Nome do perfil').fill('Perfil')
    await primary.getByLabel('Endereço da carteira').fill(`0x${'a'.repeat(40)}`)
    await primary.getByLabel('Tipo de carteira').selectOption('metamask')
    await primary.getByLabel('Código de indicação').fill('DEMO')
    await primary.getByLabel('E-mail').fill('a@kurio.test')
    await primary.getByLabel('Nome ENS').fill('colecionador')
    await primary.getByRole('button', { name: 'Salvar carteira' }).click()
    await expect(primary.getByRole('status')).toHaveText('Carteira salva.')
    await page.getByRole('button', { name: 'Igual à carteira principal' }).click()
    const secondary = page.getByRole('form', { name: 'Carteira secundária' })
    await secondary.getByLabel('Apelido da carteira').fill('Reserva')
    await secondary.getByLabel('Rede').selectOption('polygon')
    await secondary.getByRole('button', { name: 'Salvar carteira' }).click()
    await expect(secondary.getByRole('status')).toHaveText('Carteira salva.')
    await page.reload()
    await expect(primary.getByLabel('Apelido da carteira')).toHaveValue('Principal')
    await expect(secondary.getByLabel('Apelido da carteira')).toHaveValue('Reserva')
    await page.goto('http://127.0.0.1:5173/nfts/emerald-ape-042')
    await page.getByRole('button', { name: 'Comprar NFT', exact: true }).click()
    await page.getByRole('button', { name: 'Conectar e finalizar' }).click()
    await page.getByLabel(/Carteira secundária — Reserva/).click()
    await expect(page.locator('#checkout-network')).toHaveValue('polygon')
    if (width < 1280) await page.getByRole('button', { name: 'Continuar', exact: true }).click()
    await page.getByRole('button', { name: 'Conectar carteira', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Confirmar compra', exact: true })).toBeEnabled()
    await page.goto('http://127.0.0.1:5173/profile')
    if (width < 1280) await page.getByRole('button', { name: 'Meu perfil', exact: true }).click()
    await page.getByRole('button', { name: 'Sair', exact: true }).click()
    await page.goto('http://127.0.0.1:5173/login')
    await page.getByLabel('E-mail', { exact: true }).fill('colecionador.a@kurio.test')
    await page.getByLabel('Senha', { exact: true }).fill('DemoA!2026')
    await page.getByRole('button', { name: 'Entrar', exact: true }).click()
    await expect(page.locator('.auth-error')).toHaveText('E-mail ou senha inválidos')
    await page.getByLabel('Senha', { exact: true }).fill('NovaSenha!2026')
    await page.getByRole('button', { name: 'Entrar', exact: true }).click()
    await expect(page).toHaveURL('http://127.0.0.1:5173/')
  })
}
