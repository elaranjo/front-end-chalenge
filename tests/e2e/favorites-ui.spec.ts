import { expect, test } from '@playwright/test'

test('favorites require a session and persist across catalog, detail and list', async ({ page }) => {
  await page.goto('http://127.0.0.1:5173/nfts/emerald-ape-042')
  await page.getByRole('link', { name: 'Entrar para favoritar: Emerald Ape #042' }).click()
  await expect(page).toHaveURL(/\/login\?returnTo=/)
  await page.getByLabel('E-mail', { exact: true }).fill('colecionador.a@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('DemoA!2026')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(/\/nfts\/emerald-ape-042$/)
  const add = page.getByRole('button', { name: 'Adicionar aos favoritos: Emerald Ape #042' })
  await expect(add).toBeEnabled()
  const saved = page.waitForResponse((response) => response.url().endsWith('/favorites/emerald-ape-042') && response.request().method() === 'PUT' && response.ok())
  await add.click()
  await saved
  await expect(page.getByRole('button', { name: 'Remover dos favoritos: Emerald Ape #042' })).toBeVisible()
  await page.goto('http://127.0.0.1:5173/favorites')
  await expect(page.getByRole('heading', { name: 'Lista de interesse' })).toBeVisible()
  await expect(page.getByRole('link', { name: /Emerald Ape #042/ })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('link', { name: /Emerald Ape #042/ })).toBeVisible()
  const removed = page.waitForResponse((response) => response.url().endsWith('/favorites/emerald-ape-042') && response.request().method() === 'DELETE' && response.ok())
  await page.getByRole('button', { name: 'Remover dos favoritos: Emerald Ape #042' }).click()
  await removed
  await expect(page.getByText('Você ainda não tem NFTs na lista de interesse.')).toBeVisible()
  await page.reload()
  await expect(page.getByText('Você ainda não tem NFTs na lista de interesse.')).toBeVisible()
})

test('a failed optimistic favorite is rolled back and reports the error', async ({ page }) => {
  await page.goto('http://127.0.0.1:5173/nfts/emerald-ape-042?mockScenario=favorite-failure')
  await page.getByRole('link', { name: 'Entrar para favoritar: Emerald Ape #042' }).click()
  await page.getByLabel('E-mail', { exact: true }).fill('colecionador.a@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('DemoA!2026')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  const add = page.getByRole('button', { name: 'Adicionar aos favoritos: Emerald Ape #042' })
  await expect(add).toBeEnabled()
  const failed = page.waitForResponse((response) => response.url().endsWith('/favorites/emerald-ape-042') && response.request().method() === 'PUT' && response.status() === 503)
  await add.click()
  await expect(page.getByRole('button', { name: 'Remover dos favoritos: Emerald Ape #042' })).toHaveAttribute('aria-pressed', 'true')
  await failed
  await expect(page.getByRole('button', { name: 'Adicionar aos favoritos: Emerald Ape #042' })).toHaveAttribute('aria-pressed', 'false')
  await expect(page.getByRole('alert').filter({ hasText: 'Não foi possível atualizar os favoritos.' })).toBeVisible()
  await page.goto('http://127.0.0.1:5173/favorites')
  await expect(page.getByText('Você ainda não tem NFTs na lista de interesse.')).toBeVisible()
})

test('an earlier favorite failure does not report an error for a newer pending intent', async ({ page }) => {
  await page.goto('http://127.0.0.1:5173/nfts/emerald-ape-042?mockScenario=favorite-failure')
  await page.getByRole('link', { name: 'Entrar para favoritar: Emerald Ape #042' }).click()
  await page.getByLabel('E-mail', { exact: true }).fill('colecionador.a@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('DemoA!2026')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  const add = page.getByRole('button', { name: 'Adicionar aos favoritos: Emerald Ape #042' })
  await expect(add).toBeEnabled()
  await add.click()
  const remove = page.getByRole('button', { name: 'Remover dos favoritos: Emerald Ape #042' })
  await expect(remove).toHaveAttribute('aria-pressed', 'true')
  const secondRequest = page.waitForRequest((request) => request.url().endsWith('/favorites/emerald-ape-042') && request.method() === 'DELETE')
  const secondFailure = page.waitForResponse((response) => response.url().endsWith('/favorites/emerald-ape-042') && response.request().method() === 'DELETE' && response.status() === 503)
  await remove.click()
  await secondRequest
  await expect(page.getByRole('button', { name: 'Adicionar aos favoritos: Emerald Ape #042' })).toHaveAttribute('aria-pressed', 'false')
  await expect(page.getByRole('alert').filter({ hasText: 'Não foi possível atualizar os favoritos.' })).toHaveCount(0)
  await secondFailure
  await expect(page.getByRole('alert').filter({ hasText: 'Não foi possível atualizar os favoritos.' })).toBeVisible()
})

test('favorites stay isolated when switching accounts', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('http://127.0.0.1:5173/nfts/emerald-ape-042')
  await page.getByRole('link', { name: 'Entrar para favoritar: Emerald Ape #042' }).click()
  await page.getByLabel('E-mail', { exact: true }).fill('colecionador.a@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('DemoA!2026')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  const saved = page.waitForResponse((response) => response.url().endsWith('/favorites/emerald-ape-042') && response.request().method() === 'PUT' && response.ok())
  await page.getByRole('button', { name: 'Adicionar aos favoritos: Emerald Ape #042' }).click()
  await expect(page.getByRole('button', { name: 'Remover dos favoritos: Emerald Ape #042' })).toHaveAttribute('aria-pressed', 'true')
  await saved
  await page.goto('http://127.0.0.1:5173/profile')
  await page.getByRole('button', { name: 'Sair', exact: true }).click()
  await page.goto('http://127.0.0.1:5173/login?returnTo=%2Ffavorites')
  await page.getByLabel('E-mail', { exact: true }).fill('colecionador.b@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('DemoB!2026')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page.getByText('Você ainda não tem NFTs na lista de interesse.')).toBeVisible()
  await expect(page.getByRole('link', { name: /Emerald Ape #042/ })).toHaveCount(0)
  await page.getByRole('button', { name: 'Sair', exact: true }).click()
  await page.goto('http://127.0.0.1:5173/login?returnTo=%2Ffavorites')
  await page.getByLabel('E-mail', { exact: true }).fill('colecionador.a@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('DemoA!2026')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(/\/favorites$/)
  await expect(page.locator('.favorites-grid').getByRole('link', { name: /Emerald Ape #042/ })).toBeVisible()
})
