import { expect, test } from '@playwright/test'

test('wallets require login and both independently saved drafts survive refresh', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1080 })
  await page.goto('http://127.0.0.1:5173/wallets')
  await expect(page).toHaveURL(/\/login\?returnTo=%2Fwallets/)
  await page.getByLabel('E-mail', { exact: true }).fill('colecionador.a@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('DemoA!2026')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(/\/wallets$/)
  await expect(page.locator('.account-header-actions')).toHaveCSS('column-gap', '28px')
  const activeNavigation = page.locator('.wallet-header nav [aria-current="page"]')
  await expect(activeNavigation).toHaveCSS('color', 'rgb(232, 155, 85)')
  await expect(activeNavigation).toHaveCSS('border-bottom-width', '3px')
  const search = page.getByRole('button', { name: 'Buscar NFTs' })
  await expect(search.locator('img')).toHaveAttribute('src', '/assets/icons/context-43663fd7c3c84d7b.svg')
  await expect(page.locator('.account-cart img')).toHaveAttribute('src', '/assets/icons/context-5e2917db4f8f9463.svg')
  const primary = page.getByRole('form', { name: 'Carteira principal' })
  await expect(primary.getByLabel('Sufixo ENS')).toHaveValue('.eth')
  await expect(primary.getByLabel('Sufixo ENS')).toHaveCSS('background-image', /context-bd200d44e9af2433\.svg/)
  await expect(primary.getByLabel('Rede')).toHaveCSS('background-image', /wallet-select-arrow-figma\.svg/)
  await page.evaluate(() => document.fonts.ready)
  await expect(primary.locator('.wallet-fields label').first()).toHaveCSS('font-size', '15px')
  const saveButton = primary.getByRole('button', { name: 'Salvar carteira' })
  expect(await saveButton.evaluate((element) => element.scrollHeight <= element.clientHeight && element.scrollWidth <= element.clientWidth)).toBe(true)
  await page.screenshot({ path: 'tmp/wallets-desktop.png', fullPage: true })
  await search.click()
  await expect(page.getByLabel('Buscar NFTs', { exact: true }).last()).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(search).toBeFocused()
  await page.getByRole('button', { name: 'Adicionar', exact: true }).first().click()
  await expect(primary.getByLabel('Nome de exibição')).toBeFocused()
  await primary.getByRole('button', { name: 'Salvar carteira' }).click()
  await expect(primary.getByRole('alert')).toHaveText('Confira os campos destacados.')
  await expect(primary.getByLabel('Rede', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  await expect(primary.getByLabel('Endereço da carteira')).toHaveAttribute('aria-describedby', 'primary-error-address')
  await expect(primary.locator('#primary-error-address')).toContainText('40 caracteres hexadecimais')
  await primary.getByLabel('Nome de exibição').fill('Colecionador')
  await primary.getByLabel('Apelido da carteira').fill('Principal')
  await primary.getByLabel('Rede').selectOption('ethereum')
  await primary.getByLabel('Nome do perfil').fill('Perfil')
  await primary.getByLabel('Endereço da carteira').fill(`0x${'a'.repeat(40)}`)
  await primary.getByLabel('Tipo de carteira').selectOption('metamask')
  await primary.getByLabel('Código de indicação').fill('DEMO')
  await primary.getByLabel('E-mail').fill('a@kurio.test')
  await primary.getByLabel('Nome ENS').fill('colecionador')
  await primary.getByRole('button', { name: 'Salvar carteira' }).click()
  await expect(primary.getByRole('status')).toHaveText('Carteira salva.')
  await page.getByRole('button', { name: 'Igual à carteira principal' }).click()
  const secondary = page.getByRole('form', { name: 'Carteira secundária' })
  await expect(secondary.getByLabel('Sufixo ENS')).toHaveValue('.eth')
  await expect(secondary.getByLabel('Apelido da carteira')).toHaveValue('Principal')
  await secondary.getByLabel('Apelido da carteira').fill('Reserva')
  await secondary.getByRole('button', { name: 'Salvar carteira' }).click()
  await expect(secondary.getByRole('status')).toHaveText('Carteira salva.')
  await primary.getByLabel('Nome de exibição').fill('Outro nome')
  await primary.getByRole('button', { name: 'Salvar carteira' }).click()
  await expect(primary.getByRole('status')).toHaveText('Carteira salva.')
  await expect(secondary.getByLabel('Nome de exibição')).toHaveValue('Colecionador')
  await page.reload()
  await expect(page.getByRole('form', { name: 'Carteira principal' }).getByLabel('Apelido da carteira')).toHaveValue('Principal')
  await expect(page.getByRole('form', { name: 'Carteira secundária' }).getByLabel('Apelido da carteira')).toHaveValue('Reserva')
  await expect(page.getByRole('form', { name: 'Carteira principal' }).getByLabel('Nome de exibição')).toHaveValue('Outro nome')
  await expect(page.getByRole('form', { name: 'Carteira secundária' }).getByLabel('Nome de exibição')).toHaveValue('Colecionador')
})

test('wallet selectors preserve readable text contrast before and after selection', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('http://127.0.0.1:5173/wallets')
  await page.getByLabel('E-mail', { exact: true }).fill('colecionador.a@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('DemoA!2026')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  const form = page.getByRole('form', { name: 'Carteira principal' })
  const network = form.getByLabel('Rede', { exact: true })
  const walletType = form.getByLabel('Tipo de carteira', { exact: true })
  const suffix = form.getByLabel('Sufixo ENS', { exact: true })
  async function contrast(control: typeof network) {
    return control.evaluate((element) => {
      const color = (value: string) => value.match(/[\d.]+/g)!.slice(0, 3).map(Number).map((channel) => {
        const s = channel / 255
        return s <= 0.04045 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4
      })
      const luminance = (value: string) => { const [r, g, b] = color(value); return 0.2126 * r + 0.7152 * g + 0.0722 * b }
      const foreground = luminance(getComputedStyle(element).color)
      const background = luminance(getComputedStyle(element.closest('.wallet-page')!).backgroundColor)
      return (Math.max(foreground, background) + 0.05) / (Math.min(foreground, background) + 0.05)
    })
  }
  for (const width of [390, 1440]) {
    await page.setViewportSize({ width, height: 844 })
    for (const control of [network, walletType, suffix]) expect(await contrast(control)).toBeGreaterThanOrEqual(4.5)
    await network.selectOption('ethereum')
    await walletType.selectOption('metamask')
    for (const control of [network, walletType, suffix]) expect(await contrast(control)).toBeGreaterThanOrEqual(4.5)
    await network.selectOption('')
    await walletType.selectOption('')
  }
})
