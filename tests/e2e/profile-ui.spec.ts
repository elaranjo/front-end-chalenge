import { expect, test } from '@playwright/test'

test('profile validates an atomic save and persists the staged avatar and new password', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1080 })
  await page.goto('http://127.0.0.1:5173/profile')
  await expect(page).toHaveURL(/\/login\?returnTo=%2Fprofile/)
  await page.getByLabel('E-mail', { exact: true }).fill('colecionador.a@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('DemoA!2026')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Perfil do colecionador' })).toBeVisible()
  await expect(page.getByLabel('Sufixo ENS')).toHaveValue('.eth')
  await expect(page.getByLabel('Sufixo ENS')).toHaveCSS('background-image', /context-bd200d44e9af2433\.svg/)
  await expect(page.getByLabel('Nome ENS')).toBeEditable()
  const avatar = page.getByRole('img', { name: 'Sem avatar' })
  expect(await avatar.boundingBox()).toMatchObject({ width: 50, height: 50 })
  await expect(avatar.locator('img')).toHaveAttribute('src', '/assets/icons/profile-avatar-figma.svg')
  const passwordIcons = page.locator('.profile-password-icon')
  await expect(passwordIcons).toHaveCount(3)
  expect(await passwordIcons.first().boundingBox()).toMatchObject({ width: 20, height: 20 })
  await expect(passwordIcons.first().locator('img')).toHaveAttribute('src', '/assets/icons/profile-hide-figma.svg')
  await page.getByRole('button', { name: 'Mostrar senha atual' }).click()
  await expect(page.getByLabel('Senha atual', { exact: true })).toHaveAttribute('type', 'text')
  await page.getByRole('button', { name: 'Ocultar senha atual' }).click()
  await expect(page.getByLabel('Senha atual', { exact: true })).toHaveAttribute('type', 'password')
  const search = page.getByRole('button', { name: 'Buscar NFTs' })
  await search.click()
  await expect(page.getByRole('textbox', { name: 'Buscar NFTs' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(search).toBeFocused()
  await expect(page.getByRole('link', { name: 'Meu perfil', exact: true })).toBeVisible()
  await page.evaluate(() => document.fonts.ready)
  const navigation = page.locator('.wallet-header nav')
  expect((await navigation.boundingBox())?.x).toBe(496)
  await expect(navigation).toHaveCSS('font-size', '16px')
  for (const text of ['Nome de exibição', 'Nome de usuário', 'E-mail', 'Nome ENS', 'Apelido da carteira']) {
    await expect(page.locator('.profile-field > label').filter({ hasText: text })).toHaveCSS('font-size', '15px')
  }
  await page.getByRole('heading', { name: 'Perfil do colecionador' }).click()
  await page.screenshot({ path: 'tmp/profile-desktop.png', fullPage: true })
  const original = await page.getByLabel('Nome de exibição').inputValue()
  await page.getByLabel('Nome de exibição').fill('Nome atualizado')
  await page.getByLabel('Senha atual', { exact: true }).fill('incorreta')
  await page.getByLabel('Nova senha', { exact: true }).fill('NovaSenha!2026')
  await page.getByLabel('Confirmar nova senha', { exact: true }).fill('NovaSenha!2026')
  await page.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(page.getByText('Senha atual incorreta').first()).toBeVisible()
  const savedName = await page.evaluate(async () => (await (await fetch('/api/v1/profile', { headers: { Authorization: `Bearer ${localStorage.getItem('kurio.session-token')}` } })).json()).displayName)
  expect(savedName).toBe(original)
  await page.getByLabel('Senha atual', { exact: true }).fill('DemoA!2026')
  await page.locator('input[type=file]').setInputFiles({ name: 'invalido.txt', mimeType: 'text/plain', buffer: Buffer.from('invalid') })
  await expect(page.getByText('Escolha uma imagem PNG, JPEG ou WebP de até 2 MiB.')).toBeVisible()
  await page.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(page.getByText('Confira os campos destacados.')).toBeVisible()
  const image = await page.evaluate(async () => {
    const canvas = document.createElement('canvas'); canvas.width = 2; canvas.height = 2
    const blob = await new Promise<Blob>((resolve) => canvas.toBlob((value) => resolve(value!), 'image/png'))
    return Array.from(new Uint8Array(await blob.arrayBuffer()))
  })
  await page.locator('input[type=file]').setInputFiles({ name: 'avatar.png', mimeType: 'image/png', buffer: Buffer.from(image) })
  await expect(page.getByAltText('Avatar do perfil')).toBeVisible()
  await page.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Perfil salvo.')
  await page.getByLabel('Nome de exibição').fill('Nome salvo novamente')
  await page.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Perfil salvo.')
  await page.reload()
  await expect(page.getByLabel('Nome de exibição')).toHaveValue('Nome salvo novamente')
  await expect(page.getByAltText('Avatar do perfil')).toBeVisible()
  await page.getByRole('button', { name: 'Sair', exact: true }).click()
  await page.goto('http://127.0.0.1:5173/login')
  await page.getByLabel('E-mail', { exact: true }).fill('colecionador.a@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('DemoA!2026')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page.locator('.auth-error')).toHaveText('E-mail ou senha inválidos')
  await page.getByLabel('Senha', { exact: true }).fill('NovaSenha!2026')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL('http://127.0.0.1:5173/')
})

test('mobile account menu contains keyboard focus and restores its trigger', async ({ page }) => {
  await page.setViewportSize({ width: 414, height: 896 })
  await page.goto('http://127.0.0.1:5173/profile')
  await page.getByLabel('E-mail', { exact: true }).fill('colecionador.a@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('DemoA!2026')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  const trigger = page.getByRole('button', { name: 'Meu perfil', exact: true })
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: 'Menu do perfil' })
  const first = dialog.getByRole('button', { name: 'Fechar menu' })
  const last = dialog.getByRole('button', { name: 'Sair' })
  await expect(first).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(last).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(first).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(trigger).toBeFocused()
})
