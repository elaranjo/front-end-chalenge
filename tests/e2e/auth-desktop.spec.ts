import { expect, test } from '@playwright/test'

test('desktop auth is modal over the marketplace and closes safely', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('http://127.0.0.1:5173/login?returnTo=%2Fcheckout')
  const dialog = page.getByRole('dialog', { name: 'Autenticação' })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('button', { name: 'Fechar' })).toBeFocused()
  await expect(page.locator('.auth-background .home-hero')).toBeVisible()
  await expect(page.locator('.auth-background .home-card').first()).toBeVisible()
  const referenceCard = page.locator('.auth-background .home-card').filter({ hasText: 'Neon Vessel #552' })
  const rare = referenceCard.locator('.home-reference-rare')
  const referencePrice = referenceCard.locator('.home-auth-reference-price')
  await expect(rare).toHaveAttribute('aria-hidden', 'true')
  await expect(referencePrice).toHaveAttribute('aria-hidden', 'true')
  await expect(rare).toHaveText('RARO')
  await expect(referencePrice).toHaveText('2.29 ETH')
  const imageBounds = await referenceCard.locator('.home-card-image').boundingBox()
  const rareBounds = await rare.boundingBox()
  expect(rareBounds).toMatchObject({ x: imageBounds!.x, y: imageBounds!.y + 14, width: 80, height: 29 })
  await page.evaluate(async () => { await document.fonts.ready; await Promise.all([...document.images].map((image) => image.decode())) })
  await page.screenshot({ path: 'tmp/auth-login-desktop.png', fullPage: true })
  await page.keyboard.press('Escape')
  await expect(page).toHaveURL('http://127.0.0.1:5173/')
  await page.goto('http://127.0.0.1:5173/login?returnTo=%2Fcart')
  await page.getByRole('dialog').getByRole('link', { name: 'Criar conta' }).click()
  await expect(page).toHaveURL(/\/signup\?returnTo=%2Fcart/)
  await expect(page.getByRole('dialog').getByLabel('Nome de usuário')).toBeVisible()
  await expect(page.locator('.auth-background .home-card').first()).toBeVisible()
  await page.evaluate(async () => { await document.fonts.ready; await Promise.all([...document.images].map((image) => image.decode())) })
  await page.screenshot({ path: 'tmp/auth-signup-desktop.png', fullPage: true })
  await page.getByRole('dialog').getByRole('link', { name: 'Entrar', exact: true }).click()
  await page.getByRole('dialog').getByLabel('E-mail').fill('colecionador.a@kurio.test')
  await page.getByRole('dialog').getByLabel('Senha', { exact: true }).fill('DemoA!2026')
  await page.getByRole('dialog').getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(/\/cart$/)
})

for (const reference of [
  { path: '/login', top: 160, height: 600, fieldYs: [324, 376], buttonY: 468 },
  { path: '/signup', top: 158, height: 656, fieldYs: [322, 374, 426, 478], buttonY: 542 },
]) {
  test(`desktop ${reference.path} follows the Figma modal and field geometry`, async ({ page }) => {
    await page.setViewportSize({ width: 1440, height: 1080 })
    await page.goto(`http://127.0.0.1:5173${reference.path}`)
    const dialog = page.getByRole('dialog', { name: 'Autenticação' })
    await expect(dialog).toBeVisible()
    const passwordIcon = dialog.getByRole('button', { name: 'Mostrar senha', exact: true }).locator('.auth-password-icon')
    expect((await passwordIcon.boundingBox())?.height).toBe(20)
    await expect(passwordIcon.locator('img')).toHaveAttribute('src', '/assets/icons/auth-desktop-signup-hide-figma.svg')
    const bounds = await dialog.boundingBox()
    expect(bounds).toMatchObject({ x: 470, y: reference.top, width: 500, height: reference.height })
    expect(await dialog.getByRole('button', { name: 'Fechar' }).boundingBox()).toMatchObject({ x: 940, y: reference.top + 11, width: 18, height: 18 })
    const separator = dialog.locator('.auth-desktop-tabs span')
    await expect(separator).toHaveAttribute('aria-hidden', 'true')
    expect(await separator.boundingBox()).toMatchObject({ width: 1, height: 20 })
    const fields = await dialog.locator('.auth-fields input').all()
    expect(fields).toHaveLength(reference.fieldYs.length)
    for (let index = 0; index < fields.length; index++) {
      expect(await fields[index].boundingBox()).toMatchObject({ x: 550, y: reference.fieldYs[index], width: 340, height: 40 })
    }
    expect(await dialog.locator('.auth-submit').boundingBox()).toMatchObject({ x: 550, y: reference.buttonY, width: 340, height: 45 })
    const social = dialog.locator('.auth-social button')
    const firstSocial = await social.nth(0).boundingBox()
    const secondSocial = await social.nth(1).boundingBox()
    expect(secondSocial!.y - (firstSocial!.y + firstSocial!.height)).toBe(12)
    const google = social.nth(0).locator('.auth-google-desktop')
    expect(await google.boundingBox()).toMatchObject({ width: 20, height: 20 })
    const parts = google.locator('img')
    await expect(parts).toHaveCount(7)
    for (const node of [244, 245, 249, 251, 252, 253, 254]) {
      const part = google.locator(`.auth-google-${node}`)
      await expect(part).toHaveAttribute('src', `/assets/icons/google-desktop-${node}.svg`)
      expect(await part.evaluate((image: HTMLImageElement) => image.complete && image.naturalWidth > 0)).toBe(true)
    }
    await expect(social.nth(1).locator('img')).toHaveAttribute('src', `/assets/icons/${reference.path === '/signup' ? 'context-434d15ce624cf881' : 'context-989807e1d00ec515'}.svg`)
  })
}

test('desktop authentication keeps keyboard focus inside the modal', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('http://127.0.0.1:5173/login')
  const dialog = page.getByRole('dialog', { name: 'Autenticação' })
  const first = dialog.getByRole('button', { name: 'Fechar' })
  const last = dialog.getByRole('button', { name: 'Continuar com Facebook' })
  await expect(first).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(last).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(first).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page).toHaveURL('http://127.0.0.1:5173/')
})

test('closing desktop authentication restores focus to its home trigger', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('http://127.0.0.1:5173/')
  const trigger = page.locator('.home-login')
  await trigger.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('dialog', { name: 'Autenticação' })).toBeVisible()
  await page.getByRole('dialog').getByRole('link', { name: 'Criar conta' }).click()
  await expect(page).toHaveURL(/\/signup/)
  await expect(page.getByRole('dialog', { name: 'Autenticação' }).getByRole('button', { name: 'Fechar' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page).toHaveURL('http://127.0.0.1:5173/')
  await expect(trigger).toBeFocused()
})

test('direct desktop authentication close does not restore a nonexistent trigger', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('http://127.0.0.1:5173/login')
  await expect(page.getByRole('dialog', { name: 'Autenticação' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page).toHaveURL('http://127.0.0.1:5173/')
  await expect(page.locator('.home-login')).not.toBeFocused()
})

test('closing authentication opened from the cart restores its trigger', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('http://127.0.0.1:5173/cart?mockScenario=visual-desktop')
  const trigger = page.locator('.account-login')
  await trigger.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('dialog', { name: 'Autenticação' }).getByRole('button', { name: 'Fechar' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page).toHaveURL('http://127.0.0.1:5173/cart?mockScenario=visual-desktop')
  await expect(trigger).toBeFocused()
  await page.keyboard.press('Enter')
  await page.getByLabel('E-mail', { exact: true }).fill('colecionador.a@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('DemoA!2026')
  await page.getByRole('dialog').getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL('http://127.0.0.1:5173/cart?mockScenario=visual-desktop')
  await expect(page.locator('.account-login')).toContainText('Meu perfil')
})

