import { expect, test } from '@playwright/test'

test('three-item confirmed receipt retains the reference quantities and totals', async ({ page }) => {
  test.setTimeout(60000)
  await page.setViewportSize({ width: 1440, height: 1657 })
  await page.goto('http://127.0.0.1:5173/cart?mockScenario=visual-desktop')
  await expect(page.locator('.cart-line')).toHaveCount(3)
  await page.getByRole('button', { name: 'Conectar e finalizar' }).click()
  await page.getByLabel('E-mail', { exact: true }).fill('colecionador.a@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('DemoA!2026')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(/\/checkout$/)
  await page.evaluate(async () => {
    const token = localStorage.getItem('kurio.session-token')!
    const wallet = { displayName: 'Colecionador', nickname: 'Principal', network: 'ethereum', profileName: 'Perfil', address: `0x${'a'.repeat(40)}`, type: 'metamask', referralCode: 'DEMO', email: 'a@kurio.test', ensName: 'colecionador' }
    const response = await fetch('/api/v1/wallets/primary', { method: 'PUT', headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json', 'If-Match': '0' }, body: JSON.stringify(wallet) })
    if (!response.ok) throw new Error(`wallet ${response.status}`)
  })
  await page.reload()
  await page.getByLabel(/Carteira principal — Principal/).click()
  await page.getByLabel('Coinbase Wallet').check()
  await page.getByRole('button', { name: 'Conectar carteira' }).click()
  await expect(page.getByRole('button', { name: 'Confirmar compra' })).toBeEnabled()
  await expect(page.locator('.checkout-item')).toHaveCount(3)
  await expect(page.locator('.checkout-totals')).toContainText('26.846 ETH')
  await expect(page.locator('.checkout-item-total').first()).toHaveCSS('font-size', '18px')
  await expect(page.locator('.checkout-totals > div').last().locator('dd')).toHaveCSS('font-size', '18px')
  await page.evaluate(async () => { await document.fonts.ready; await Promise.all([...document.images].map((image) => image.decode())) })
  await page.screenshot({ path: 'tmp/checkout-reference-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Desconectar carteira', exact: true }).click()
  await page.getByRole('radio', { name: 'MetaMask', exact: true }).check()
  await page.getByRole('button', { name: 'Conectar carteira', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Confirmar compra' })).toBeEnabled()
  await page.getByRole('button', { name: 'Confirmar compra' }).click()
  await expect(page.getByRole('heading', { name: 'Seus NFTs agora estão na sua carteira' })).toBeVisible({ timeout: 15000 })
  const items = page.locator('.order-item')
  await expect(items).toHaveCount(3)
  await expect(items.nth(0)).toContainText('2.38 ETH')
  await expect(items.nth(1)).toContainText('8.34 ETH')
  await expect(items.nth(2)).toContainText('16.11 ETH')
  await expect(page.locator('.order-totals')).toContainText('26.846 ETH')
  await expect(page.locator('.order-metadata')).toContainText('MetaMask')
  await page.evaluate(async () => { await document.fonts.ready; await Promise.all([...document.images].map((image) => image.decode())) })
  await page.screenshot({ path: 'tmp/order-reference-desktop.png', fullPage: true })
})
